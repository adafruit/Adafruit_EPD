class ThinkInk_426_Grayscale4_X4PRO : public Adafruit_UC8279 {
 public:
  ThinkInk_426_Grayscale4_X4PRO(int16_t SID, int16_t SCLK, int16_t DC,
                                int16_t RST, int16_t CS, int16_t SRCS,
                                int16_t MISO, int16_t BUSY = -1)
      : Adafruit_UC8279(800, 480, SID, SCLK, DC, RST, CS, SRCS, MISO, BUSY) {};

  ThinkInk_426_Grayscale4_X4PRO(int16_t DC, int16_t RST, int16_t CS,
                                int16_t SRCS, int16_t BUSY = -1,
                                SPIClass* spi = &SPI)
      : Adafruit_UC8279(800, 480, DC, RST, CS, SRCS, BUSY, spi) {};

  void begin(thinkinkmode_t mode = THINKINK_MONO) {
    Adafruit_UC8279::begin(true);

    inkmode = mode;

    if (mode == THINKINK_GRAYSCALE4) {
      // Per pixel (OLD, NEW) plane bits: white (0,0), light gray (1,0),
      // dark gray (0,1), black (1,1). Layer bit 0 goes to buffer2, which is
      // written to the OLD plane, and bit 1 to buffer1 (NEW plane).
      setBlackBuffer(1, false);
      setColorBuffer(0, false);

      _epd_lut_code = ti_426_x4pro_gray4_lut_code;
      _blank_fill = 0x00; // (0,0) is white in this encoding

      layer_colors[EPD_WHITE] = 0b00;
      layer_colors[EPD_BLACK] = 0b11;
      layer_colors[EPD_RED] = 0b01;
      layer_colors[EPD_GRAY] = 0b10;
      layer_colors[EPD_LIGHT] = 0b01;
      layer_colors[EPD_DARK] = 0b10;
    } else {
      // THINKINK_MONO: the driver defaults, OTP waveform
      _epd_lut_code = NULL;
      _blank_fill = 0xFF;
    }
  }
};

